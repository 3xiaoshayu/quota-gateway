// Maps the upstream stylesheet's hash-named colour variables (light-theme
// originals such as --theme-2d2a26) onto the Quota Switcher dark palette by
// role, and writes the block that src/theme-quota.css starts with.
//
//   bun run scripts/generate-theme-tokens.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const stylesheet = await readFile(join(root, 'src', 'styles.css'), 'utf8');

// Upstream named each variable after its light-theme hex, so the names still
// referenced by the stylesheet are the complete list of originals.
const names = [...new Set([...stylesheet.matchAll(/var\(--theme-([0-9a-f]{3,6})\b/g)].map(([, name]) => name))].sort();
const originals = names.map((name) => [name, name.length === 3 ? name.replace(/(.)/g, '$1$1') : name]);

const palette = {
  base: '#131315',
  surface: '#1c1c1e',
  surface2: '#242426',
  surface3: '#2c2c2f',
  fill: 'rgba(255, 255, 255, 0.055)',
  fill2: 'rgba(255, 255, 255, 0.09)',
  fill3: 'rgba(255, 255, 255, 0.14)',
  fill4: 'rgba(255, 255, 255, 0.22)',
  label: 'rgba(255, 255, 255, 0.96)',
  label2: 'rgba(235, 235, 245, 0.62)',
  label3: 'rgba(235, 235, 245, 0.34)',
  sep: 'rgba(255, 255, 255, 0.075)',
  accent: '#0a84ff',
  accentHi: '#409cff',
  ok: '#30d158',
  warn: '#ff9f0a',
  danger: '#ff453a',
  purple: '#bf5af2',
};

function hsl(hex) {
  const r = parseInt(hex.slice(0, 2), 16) / 255;
  const g = parseInt(hex.slice(2, 4), 16) / 255;
  const b = parseInt(hex.slice(4, 6), 16) / 255;
  const max = Math.max(r, g, b);
  const min = Math.min(r, g, b);
  const l = (max + min) / 2;
  const d = max - min;
  const s = d === 0 ? 0 : d / (1 - Math.abs(2 * l - 1));
  let h = 0;
  if (d !== 0) {
    if (max === r) h = ((g - b) / d) % 6;
    else if (max === g) h = (b - r) / d + 2;
    else h = (r - g) / d + 4;
    h = (h * 60 + 360) % 360;
  }
  return { h, s, l };
}

function tint(color, alpha) {
  const r = parseInt(color.slice(1, 3), 16);
  const g = parseInt(color.slice(3, 5), 16);
  const b = parseInt(color.slice(5, 7), 16);
  return `rgba(${r}, ${g}, ${b}, ${alpha})`;
}

function semanticFor(h) {
  if (h >= 75 && h < 170) return palette.ok;
  if (h >= 170 && h < 260) return palette.accent;
  if (h >= 260 && h < 330) return palette.purple;
  if (h >= 330 || h < 20) return palette.danger;
  return palette.warn;
}

function mapColor(hex) {
  const { h, s, l } = hsl(hex);
  // Warm greys and the near-white creams upstream used for panels and hover
  // fills are neutrals; only clearly tinted colours are semantic. A real
  // warning yellow (#fff7e9) is fully saturated, a cream (#faf8f2) is not.
  const warm = h >= 20 && h < 60;
  const cream = warm && l > 0.93 && s >= 0.32 && s < 0.6;
  // Creams were inner panels and hover fills on a white card; on a dark
  // surface that layer is the translucent fill, one step lighter than the card.
  if (cream) return palette.fill;
  const tinted = s > 0.22 && !(warm && s < 0.32);
  if (tinted) {
    const colour = semanticFor(h);
    if (l < 0.45) return colour;
    if (l < 0.62) return colour === palette.accent ? palette.accentHi : colour;
    if (l < 0.8) return tint(colour, 0.32);
    if (l < 0.93) return tint(colour, 0.18);
    return tint(colour, 0.12);
  }
  if (l < 0.22) return palette.label;
  if (l < 0.34) return 'rgba(255, 255, 255, 0.86)';
  if (l < 0.46) return palette.label2;
  if (l < 0.56) return 'rgba(235, 235, 245, 0.5)';
  if (l < 0.66) return palette.label3;
  if (l < 0.78) return palette.fill4;
  if (l < 0.86) return palette.fill3;
  if (l < 0.905) return palette.surface3;
  if (l < 0.95) return palette.surface2;
  if (l < 0.985) return palette.surface;
  return palette.surface;
}

const overrides = {
  // Page and window backgrounds sit on the window base, cards on surface.
  faf9f5: palette.base,
  f0eee8: palette.base,
  fff: palette.surface,
  ffffff: palette.surface,
  fffdf8: palette.surface,
  // Upstream marked a configured agent with a golden dot; here "configured"
  // is the accent, the same blue Quota Switcher uses for the current account.
  bf8a43: palette.accent,
};

const lines = originals.map(([name, hex]) => {
  const value = overrides[name] ?? mapColor(hex);
  return `  --theme-${name}: ${value};`;
});

const output = `/* Generated by scripts/generate-theme-tokens.mjs; edit that script, not this block. */
:root,
:root[data-theme='dark'] {
  --ui-accent: ${palette.accent};
  --ui-accent-strong: ${palette.accentHi};
  --ui-accent-soft: ${tint(palette.accent, 0.16)};
  --ui-focus-ring: ${tint(palette.accent, 0.4)};
  --ui-accent-shadow: rgba(0, 0, 0, 0.001);
  --ui-panel-shadow: none;
${lines.join('\n')}
}
`;

const target = join(root, 'src', 'theme-tokens.css');
await writeFile(target, output);
console.log(`Wrote ${originals.length} variables to ${target}`);
